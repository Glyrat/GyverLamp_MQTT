#pragma once

#include <Arduino.h>
#include <FastLED.h>

// ============================================================
//  НАСТРОЙКИ ОДНОГО ЭФФЕКТА
// ============================================================
struct EffectSettings {
    uint8_t brightness;   // 1..255
    uint8_t speed;        // 0..255
    uint8_t scale;        // 0..100 (у некоторых 0..255)
};

// ============================================================
//  ДЕСКРИПТОР ЭФФЕКТА
// ============================================================
struct Effect {
    const char* name;       // отображаемое имя (для веба и HA)
    void (*routine)();      // функция отрисовки
    bool usesSpeed;         // показывать ли слайдер "Скорость"
    bool usesScale;         // показывать ли слайдер "Масштаб"
};

// ============================================================
//  ОДИН ДЕНЬ БУДИЛЬНИКА
// ============================================================
enum AfterMode : uint8_t {
    AFTER_ON    = 0,   // оставить включённой
    AFTER_OFF   = 1,   // выключить
    AFTER_DELAY = 2    // выключить через N минут
};

struct AlarmDay {
    bool      enabled;        // будильник на этот день включён
    uint8_t   hour;           // 0..23
    uint8_t   minute;         // 0..59
    uint8_t   dawnMinutes;    // длительность рассвета, 1..60
    uint8_t   maxBrightness;  // максимальная яркость рассвета, 1..255
    AfterMode afterMode;      // что делать после будильника
    uint8_t   afterDelay;     // задержка выключения, 1..60 мин (для AFTER_DELAY)
};

// ============================================================
//  ГЛОБАЛЬНЫЕ НАСТРОЙКИ СИСТЕМЫ (сохраняются в /config.json)
// ============================================================
struct SystemConfig {
    int8_t   currentMode;     // индекс текущего эффекта
    bool     ONflag;          // включена ли лампа
    uint8_t  version;         // версия схемы JSON (для миграции)
};

// ============================================================
//  НАСТРОЙКИ WI-FI (/wifi.json)
// ============================================================
struct WifiConfig {
    char ssid[33];
    char pass[65];
};

// ============================================================
//  НАСТРОЙКИ MQTT (/mqtt.json)
// ============================================================
struct MqttConfig {
    char    host[64];
    uint16_t port;
    char    user[32];
    char    pass[32];
    bool    enabled;
};

// ============================================================
//  СЧЁТЧИК ПЕРЕЗАГРУЗОК (/boot.json)
// ============================================================
struct BootConfig {
    uint8_t  count;           // количество быстрых перезагрузок
    uint32_t lastBootMs;      // millis последней загрузки
};

// ============================================================
//  ОТЛОЖЕННОЕ СОХРАНЕНИЕ
// ============================================================
// Вызывается при любом изменении настроек (яркость, режим, RGB и т.д.).
// Реализация — в lamp_10.ino.
void markSettingsChanged();
