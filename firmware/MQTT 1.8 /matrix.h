#pragma once

#include <Arduino.h>
#include <FastLED.h>
#include "config.h"
#include "types.h"

// ============================================================
//  ВНЕШНИЙ БУФЕР СВЕТОДИОДОВ (определён в главном .ino)
// ============================================================
extern CRGB leds[NUM_LEDS];

// ============================================================
//  БАЗОВЫЕ ОПЕРАЦИИ
// ============================================================
// Номер пикселя в ленте по координатам (x,y).
uint16_t matrix_pixelNumber(int8_t x, int8_t y);

// Отрисовка одного пикселя по координатам. Игнорирует выход за границы.
void matrix_drawPixel(int8_t x, int8_t y, const CRGB& color);

// Отрисовка одного пикселя по координатам с учётом SEGMENTS.
void matrix_drawPixelSeg(int8_t x, int8_t y, const CRGB& color);

// Получить цвет пикселя по его номеру (0 если вне диапазона).
uint32_t matrix_getPixel(uint16_t idx);

// Получить цвет пикселя по координатам.
uint32_t matrix_getPixelXY(int8_t x, int8_t y);

// ============================================================
//  ЗАЛИВКА / ОЧИСТКА
// ============================================================
void matrix_fillAll(const CRGB& color);
void matrix_clear();

// Затемнение всех пикселей на value (0..255).
void matrix_dimAll(uint8_t value);

// Затемнение одного пикселя (i,j) на step.
void matrix_fadePixel(uint8_t i, uint8_t j, uint8_t step);

// Плавное угасание всей матрицы (для эффектов вроде конфетти).
void matrix_fader(uint8_t step);

// ============================================================
//  СУБПИКСЕЛЬНАЯ ОТРИСОВКА (для float-координат)
// ============================================================
// Рисует точку с нецелыми координатами (x,y), распределяя цвет
// между четырьмя соседними пикселями.
void matrix_drawPixelXYF(float x, float y, const CRGB& color);

// ============================================================
//  УТИЛИТЫ
// ============================================================
// Быстрый неточный корень (для некоторых эффектов).
float matrix_sqrt3(const float x);

// 2D-размытие (для эффекта "пейнтбол").
void matrix_blur2d(uint8_t amount);

// XY() из оригинального кода — «зигзаг/параллель» для внешних эффектов.
uint16_t XY(uint8_t x, uint8_t y);
