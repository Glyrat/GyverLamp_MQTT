#pragma once

#include <Arduino.h>
#include <ESP8266WiFi.h>
#include "types.h"

// ============================================================
//  СОСТОЯНИЕ
// ============================================================
extern bool wifiMgr_inAP;             // сейчас в AP-режиме (портал)
extern bool wifiMgr_apHasClient;      // клиент подключился к AP
extern bool wifiMgr_connected;        // подключены к Wi-Fi (STA)

// ============================================================
//  ИНИЦИАЛИЗАЦИЯ
// ============================================================
// Проверяет boot count, пытается подключиться к сохранённому SSID,
// при неудаче — поднимает AP-портал.
// Вызывается из setup() после storage_init() и FastLED init.
void wifiMgr_init();

// ============================================================
//  ТИКЕР
// ============================================================
// Вызывать из loop() часто (каждые 50-100 мс).
//  - в AP-режиме: раз в 30 сек пытается подключиться к сохранённому SSID
//  - обрабатывает веб-запросы портала
//  - сигналит индикацией
void wifiMgr_tick();

// ============================================================
//  ИНДИКАЦИЯ
// ============================================================
// Радужная волна + затухание (нормальный старт).
void wifiMgr_showStartupAnim();

// ============================================================
//  ИНФО (для веба/MQTT)
// ============================================================
String  wifiMgr_getSsid();
String  wifiMgr_getIp();
int     wifiMgr_getRssi();
uint8_t wifiMgr_getRssiPercent();
int     wifiMgr_getChannel();

// ============================================================
//  УПРАВЛЕНИЕ
// ============================================================
// Забыть сеть (удалить /wifi.json) и перезагрузиться в AP.
void wifiMgr_resetAndReboot();

// Попытка подключиться к переданной сети (например, из портала).
// Возвращает true при успехе.
bool wifiMgr_tryConnect(const char* ssid, const char* pass);

// Сохранить сеть в /wifi.json и подключиться.
bool wifiMgr_saveAndConnect(const char* ssid, const char* pass);

// ============================================================
//  ВНУТРЕННЕЕ (для портала)
// ============================================================
// Нарисовать пульсирующий синий один кадр. Не блокирует.
void wifiMgr_drawAPFrame();

// Нарисовать зелёный мигающий один кадр (клиент пришёл).
void wifiMgr_drawClientFrame();